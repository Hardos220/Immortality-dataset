def assert_no_duplicate_keys(path):
    """Проверка таблиц правок на повторный ключ.

    Словарь-литерал с двумя одинаковыми ключами Python принимает молча:
    побеждает последнее вхождение, первое исчезает без следа и без ошибки.
    Для таблиц правок это означает потерянную правку — ровно так уже
    пропала поправка к F256, объявленная выше по файлу, чем прежняя.
    Проверяется по разбору собственного исходника.
    """
    import ast
    with _io.open(path, encoding="utf-8") as fh:
        tree = ast.parse(fh.read(), path)
    dup = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.Dict):
            continue
        seen = {}
        for k in node.keys:
            if isinstance(k, ast.Constant) and isinstance(k.value, str):
                if k.value in seen:
                    dup.append((k.value, seen[k.value], k.lineno))
                seen[k.value] = k.lineno
    if dup:
        name = _os.path.basename(path)
        raise SystemExit(
            "%s: повторный ключ в словаре — правка молча теряется:\n%s"
            % (name, "\n".join("  «%s»: строки %d и %d" % d for d in dup)))


def normalize_indicator(name, year, country):
    """Имя показателя без того, что уже записано в соседних полях."""
    m = _YEAR_TAIL.search(name)
    if m:
        in_name = [g for g in m.groups() if g]
        in_row = _re.findall(r"\d{4}", str(year or ""))
        if in_name and all(y in in_row for y in in_name):
            stripped = _YEAR_TAIL.sub("", name).strip("_")
            if stripped:
                name = stripped

    for suffix, allowed in COUNTRY_SUFFIX.items():
        if name.endswith(suffix):
            if country in allowed:
                stripped = name[:-len(suffix)].strip("_")
                if stripped:
                    name = stripped
            break
    return name
